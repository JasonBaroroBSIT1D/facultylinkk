"""Write docs/KRA2_CRITERION_C_COVERAGE_MATRIX.md (25 indicators)."""

from __future__ import annotations

import sys
from pathlib import Path

_BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_BACKEND))

from documents.kra2_evidence.kra2_c_evidence_slots import criterion_c_required_slots, criterion_c_slot_label
from kra_configuration.kra2_c_workflow import coverage_row, criterion_c_metadata_label, criterion_c_subfamily
from kra_configuration.kra2_indicator_registry import indicators_for_criterion

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "KRA2_CRITERION_C_COVERAGE_MATRIX.md"


def main() -> None:
    ids = [r["id"] for r in indicators_for_criterion("kra2-c")]
    assert len(ids) == 25, len(ids)
    lines = [
        "# KRA II Criterion C — 25-indicator workflow coverage matrix",
        "",
        "Generated by `backend/scripts/generate_kra2_c_coverage_matrix.py`.",
        "Official rules: DBM–CHED JC No. 01, s. 2026 §§25–27, Annex A (pp. 84–92).",
        "",
        "## Implementation status legend",
        "",
        "| Code | Meaning |",
        "|---|---|",
        "| **PASS** | Automated test coverage for slots, metadata labels, OCR routing |",
        "| **NOT TESTED** | Live Faculty Mobile / Reviewer Web device or browser QA |",
        "",
        "## Coverage matrix",
        "",
        "| # | Indicator | Subfamily | OCR parser | Metadata (title / creator / venue / date) | Evidence slots | Workflow |",
        "|---:|---|---|---|---|---|---|",
    ]
    for n, iid in enumerate(ids, 1):
        row = coverage_row(iid)
        slots = criterion_c_required_slots(iid)
        slot_desc = "; ".join(f"`{s}` ({criterion_c_slot_label(s, indicator_id=iid)})" for s in slots)
        meta = " / ".join(
            criterion_c_metadata_label(f, iid)
            for f in ("outputTitle", "authorsLine", "outputVenue", "publicationDate")
        )
        lines.append(
            f"| {n} | `{iid}` | {criterion_c_subfamily(iid)} | {row['ocrParser']} | {meta} | {slot_desc} | API checklist + shared Check screen |"
        )
    lines.extend(
        [
            "",
            "## OCR coverage by subfamily",
            "",
            "| Subfamily | Parser | Sample extracted fields |",
            "|---|---|---|",
            "| music_composition / music_production | music_work | title, composer/producer, venue, date |",
            "| music_performance / dance / theater | performance | title, performer, venue, date |",
            "| visual_arts / design_exhibition | exhibition | artwork title, artist, gallery, date |",
            "| film | film | film title, director, festival, screening date |",
            "| literary | literary | work title, author, publisher, publication date |",
            "",
            "## Test matrix (automated)",
            "",
            "- Backend: `test_kra2_criterion_c_workflow_matrix.py`, `test_kra2_criterion_c_checklist_sync.py`, `test_kra2_criterion_c_ocr_routing.py`",
            "- Mobile: `mobile/test/kra2_criterion_c_all_indicators_test.dart`",
            "",
            "## Live QA",
            "",
            "Faculty Mobile and Reviewer Web end-to-end runs per indicator: **NOT TESTED** (requires credentials and manual upload fixtures).",
            "",
        ]
    )
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
